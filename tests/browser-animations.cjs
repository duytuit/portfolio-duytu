const assert=require('node:assert/strict');
const {chromium}=require('playwright');
const base=(process.env.BASE_URL || 'http://127.0.0.1:5000').replace(/\/$/, '');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE || undefined,headless:true,args:['--no-sandbox']});
 const errors=[];
 const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:'no-preference'});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/',{waitUntil:'load'});
 await page.waitForFunction(()=>document.documentElement.classList.contains('aos-enabled'));
 const target=page.locator('#portfolio .project-card').first();
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('#portfolio .project-card')).opacity==='0');
 await page.locator('#portfolio').evaluate(e=>e.scrollIntoView({behavior:'instant',block:'start'}));
 await page.waitForFunction(()=>document.querySelector('#portfolio .project-card').classList.contains('aos-animate'));
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('#portfolio .project-card')).opacity==='1');
 assert(await page.evaluate(()=>gsap.getTweensOf(document.querySelector('[data-floating-note]')).length>0));
 const tweenStart=await page.locator('[data-floating-note]').first().evaluate(e=>e.style.transform);
 await page.waitForFunction(previous=>document.querySelector('[data-floating-note]').style.transform!==previous,tweenStart);
 assert(await page.locator('[data-floating-note]').first().evaluate(e=>getComputedStyle(e).animationName==='none'));
 assert(await page.locator('[data-reading-progress]').evaluate(e=>e.style.transform!=='scaleX(0)'));
 await page.waitForFunction(()=>document.querySelector('.desktop-nav a[href="/#portfolio"]').getAttribute('aria-current')==='location');
 console.log('PASS reading progress and active navigation');
 console.log('PASS AOS reveals offscreen portfolio on scroll; GSAP moves hero without duplicate CSS animation');
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.waitForFunction(()=>gsap.getTweensOf(document.querySelector('[data-floating-note]')).length===0);
 assert(await target.evaluate(e=>getComputedStyle(e).opacity==='1'&&getComputedStyle(e).transform==='none'));
 console.log('PASS live reduced-motion preference stops GSAP and shows AOS content');
 const reduced=await browser.newPage({reducedMotion:'reduce'});
 await reduced.goto(base+'/',{waitUntil:'load'});
 assert(await reduced.locator('#portfolio [data-aos]').first().evaluate(e=>getComputedStyle(e).opacity==='1'));
 assert.equal(await reduced.evaluate(()=>gsap.getTweensOf(document.querySelector('[data-floating-note]')).length),0);
 console.log('PASS reduced motion at startup');
 const fallback=await browser.newPage();
 await fallback.route('**/lib/{aos,gsap}/**',route=>route.abort());
 await fallback.goto(base+'/',{waitUntil:'load'});
 assert(await fallback.locator('#portfolio [data-aos]').first().evaluate(e=>getComputedStyle(e).opacity==='1'));
 console.log('PASS failed library loads keep content visible');
 const nojs=await browser.newPage({javaScriptEnabled:false});
 await nojs.goto(base+'/',{waitUntil:'load'});
 assert(await nojs.locator('#portfolio [data-aos]').first().evaluate(e=>getComputedStyle(e).opacity==='1'));
 console.log('PASS JavaScript disabled keeps content visible');
 await page.emulateMedia({reducedMotion:'no-preference'});
 await page.setViewportSize({width:390,height:844});
 await page.goto(base+'/',{waitUntil:'load'});
 await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
 await page.locator('[data-menu-open]').click();assert(await page.locator('#mobile-menu').isVisible());
 await page.locator('#mobile-menu a[href="/#about"]').click();assert(!await page.locator('#mobile-menu').isVisible());
 await page.locator('#portfolio').evaluate(e=>e.scrollIntoView({behavior:'instant'}));
 await page.waitForFunction(()=>document.querySelector('#portfolio .project-card').classList.contains('aos-animate'));
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 console.log('PASS mobile scroll animation, menu and no horizontal overflow');
 assert.deepEqual(errors,[]);console.log('PASS no browser JavaScript errors');
 await page.evaluate(()=>scrollTo({top:0,behavior:'instant'}));
 await page.screenshot({path:'/tmp/portfolio-vivid-mobile.png'});
 await page.setViewportSize({width:1440,height:1000});
 await page.goto(base+'/',{waitUntil:'load'});
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('.hero-copy')).opacity==='1');
 await page.screenshot({path:'/tmp/portfolio-vivid-desktop.png'});
 await page.locator('[data-theme-toggle]').click();
 assert.equal(await page.evaluate(()=>document.documentElement.dataset.theme),'dark');
 await page.screenshot({path:'/tmp/portfolio-vivid-dark.png'});
 console.log('PASS theme toggle');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
